    const spriteCache = {};

    function getCharacterSprites(paletteIndex) {
        const key = String(paletteIndex);
        if (spriteCache[key]) return spriteCache[key];

        const pal = CHARACTER_PALETTES[paletteIndex % CHARACTER_PALETTES.length];
        const r = (t) => resolveTemplate(t, pal);

        const sprites = {
            walk: [r(CHAR_WALK_DOWN_1), r(CHAR_WALK_DOWN_2), r(CHAR_WALK_DOWN_3), r(CHAR_WALK_DOWN_2)],
            typing: [r(CHAR_DOWN_TYPE_1), r(CHAR_DOWN_TYPE_2)],
            reading: [r(CHAR_DOWN_READ_1), r(CHAR_DOWN_READ_2)],
        };
        spriteCache[key] = sprites;
        return sprites;
    }

    function drawSprite(ctx, sprite, x, y, scale) {
        const s = scale || 2;
        ctx.imageSmoothingEnabled = false;
        for (let r = 0; r < sprite.length; r++) {
            for (let c = 0; c < sprite[r].length; c++) {
                const color = sprite[r][c];
                if (!color) continue;
                ctx.fillStyle = color;
                ctx.fillRect(Math.round(x + c * s), Math.round(y + r * s), s, s);
            }
        }
    }

